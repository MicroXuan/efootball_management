CREATE TABLE `transfer_proposals` (
  `id` CHAR(36) NOT NULL,
  `league_id` CHAR(36) NOT NULL,
  `season_id` CHAR(36) NOT NULL,
  `ownership_id` CHAR(36) NOT NULL,
  `source_team_id` CHAR(36) NOT NULL,
  `target_team_id` CHAR(36) NOT NULL,
  `initiator_team_id` CHAR(36) NOT NULL,
  `initiator_user_id` CHAR(36) NOT NULL,
  `counterparty_user_id` CHAR(36) NULL,
  `expected_ownership_version` INT UNSIGNED NOT NULL,
  `amount_minor` INT UNSIGNED NOT NULL,
  `status` ENUM('PENDING_COUNTERPARTY','PENDING_ADMIN','REJECTED','WITHDRAWN','APPROVED','EXPIRED','INVALIDATED') NOT NULL DEFAULT 'PENDING_COUNTERPARTY',
  `reason` VARCHAR(512) NULL,
  `review_reason` VARCHAR(512) NULL,
  `reviewed_by_admin_id` CHAR(36) NULL,
  `reviewed_at` DATETIME(3) NULL,
  `version` INT UNSIGNED NOT NULL DEFAULT 1,
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` DATETIME(3) NOT NULL,
  PRIMARY KEY (`id`),
  INDEX `transfer_proposals_queue_idx` (`league_id`,`status`,`created_at`),
  INDEX `transfer_proposals_source_idx` (`source_team_id`,`status`),
  INDEX `transfer_proposals_target_idx` (`target_team_id`,`status`),
  INDEX `transfer_proposals_ownership_idx` (`ownership_id`,`status`),
  CONSTRAINT `transfer_proposals_league_id_fkey` FOREIGN KEY (`league_id`) REFERENCES `leagues`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `transfer_proposals_season_id_fkey` FOREIGN KEY (`season_id`) REFERENCES `league_seasons`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `transfer_proposals_ownership_id_fkey` FOREIGN KEY (`ownership_id`) REFERENCES `league_player_ownerships`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `transfer_proposals_source_team_id_fkey` FOREIGN KEY (`source_team_id`) REFERENCES `league_teams`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `transfer_proposals_target_team_id_fkey` FOREIGN KEY (`target_team_id`) REFERENCES `league_teams`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `transfer_proposals_initiator_team_id_fkey` FOREIGN KEY (`initiator_team_id`) REFERENCES `league_teams`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `transfer_proposal_events` (
  `id` CHAR(36) NOT NULL,
  `proposal_id` CHAR(36) NOT NULL,
  `from_status` ENUM('PENDING_COUNTERPARTY','PENDING_ADMIN','REJECTED','WITHDRAWN','APPROVED','EXPIRED','INVALIDATED') NULL,
  `to_status` ENUM('PENDING_COUNTERPARTY','PENDING_ADMIN','REJECTED','WITHDRAWN','APPROVED','EXPIRED','INVALIDATED') NOT NULL,
  `actor_user_id` CHAR(36) NULL,
  `actor_admin_id` CHAR(36) NULL,
  `reason` VARCHAR(512) NULL,
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  INDEX `transfer_proposal_events_timeline_idx` (`proposal_id`,`created_at`,`id`),
  CONSTRAINT `transfer_proposal_events_proposal_id_fkey` FOREIGN KEY (`proposal_id`) REFERENCES `transfer_proposals`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
