"""OS-owned lock: released even after a crash, never delete the lock file."""
from contextlib import contextmanager
import os
from pathlib import Path
import tempfile


@contextmanager
def bridge_process_lock(path: Path | None = None):
    path = path or Path(tempfile.gettempdir()) / 'efm-wechat-bridge.lock'
    with path.open('a+b') as handle:
        if path.stat().st_size == 0:
            handle.write(b'0')
            handle.flush()
        handle.seek(0)
        try:
            if os.name == 'nt':
                import msvcrt
                msvcrt.locking(handle.fileno(), msvcrt.LK_NBLCK, 1)
            else:
                import fcntl
                fcntl.flock(handle.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
        except OSError as error:
            raise RuntimeError('BRIDGE_ALREADY_RUNNING') from error
        try:
            yield
        finally:
            handle.seek(0)
            if os.name == 'nt':
                msvcrt.locking(handle.fileno(), msvcrt.LK_UNLCK, 1)
            else:
                fcntl.flock(handle.fileno(), fcntl.LOCK_UN)
